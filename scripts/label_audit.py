"""Label audit of benign rows -> data/processed/label_audit.csv, results/label_audit.md/.json.

Scans every benign row (English sources + Gemini translations) of train, dev and the test sets for
(a) jailbreak markers (regex on the text and, for translations, the English original), except wildjailbreak
    "adversarial_benign" rows (benign by design: e5 check only);
(b) multilingual-e5-small cosine > 0.95 to any attack row (all splits, all languages).
Policy (applied in scripts/build_v3_data.py): flagged rows are dropped from TRAIN and DEV, never relabelled;
TEST sets are unchanged and evaluated with and without flagged rows.

  python -m scripts.label_audit   # training image, GPU"""
import csv, json, re
from collections import Counter
from pathlib import Path

ROOT = Path("data/processed")
FILES = {"train": ["train_public_v2.jsonl", "translated_v2_gemini.jsonl"],
         "dev": ["dev_public_v2.jsonl", "dev_translated_v2_gemini.jsonl"],
         "test": ["external_eval.jsonl", "external_translated_gemini.jsonl"],
         "overrefusal": ["overrefusal_eval.jsonl", "overrefusal_translated_gemini.jsonl"],
         "email_probe": ["benign_email_probe.jsonl"]}
TEST_SPLITS = ("test", "overrefusal", "email_probe")
MARKERS = re.compile(r"\bDAN\b|do anything now|developer mode|jailbreak|ignore (?:all|previous) (?:rules|instructions)"
                     r"|no longer (?:need to )?follow|free from (?:any )?rules|openai(?:'s)? (?:rules|policies|guidelines)", re.I)
E5 = "intfloat/multilingual-e5-small"
SIM = 0.95
OUT = ROOT/"label_audit.csv"


def read(name):
    return [json.loads(x) for x in (ROOT/name).read_text(encoding="utf-8").splitlines() if x.strip()]


def text(r):
    return r.get("text") or "\n".join(t["content"] if isinstance(t, dict) else str(t) for t in (r.get("turns") or []))


def rows_by_split():
    return {split: [r for f in files for r in read(f)] for split, files in FILES.items()}


def regex_reason(r):
    if r.get("orig_label") == "adversarial_benign":
        return None
    for field in ("text", "original"):
        m = MARKERS.search(text(r) if field == "text" else (r.get("original") or ""))
        if m:
            return f"regex:{m.group(0)[:40]}" + ("" if field == "text" else " (in original)")
    return None


def e5_flags(benign, attacks):
    import faiss, torch
    from sentence_transformers import SentenceTransformer
    model = SentenceTransformer(E5, device="cuda" if torch.cuda.is_available() else "cpu")
    enc = lambda rs: model.encode(["query: " + text(r)[:2000] for r in rs], batch_size=128, normalize_embeddings=True,
                                  show_progress_bar=True).astype("float32")
    index = faiss.IndexFlatIP(384); index.add(enc(attacks))
    sims, idx = index.search(enc(benign), 1)
    return {b["id"]: (float(s[0]), attacks[i[0]]["id"]) for b, s, i in zip(benign, sims, idx) if s[0] > SIM}


def main():
    splits = rows_by_split()
    benign = [(split, r) for split, rs in splits.items() for r in rs if r["label"] == "benign"]
    attacks = [r for rs in splits.values() for r in rs if r["label"] == "attack"]
    near = e5_flags([r for _, r in benign], attacks)
    flagged = []
    for split, r in benign:
        reasons = [x for x in (regex_reason(r), f"e5>{SIM}:{near[r['id']][0]:.3f}~{near[r['id']][1]}" if r["id"] in near else None) if x]
        if reasons:
            flagged.append({"id": r["id"], "source": r["source"], "split": split, "lang": r["lang"],
                            "reason": "; ".join(reasons), "text": text(r)[:200]})
    with OUT.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["id", "source", "split", "lang", "reason", "text"]); w.writeheader(); w.writerows(flagged)
    benign_n = Counter((r["source"], split) for split, r in benign)
    counts = Counter((x["source"], x["split"]) for x in flagged)
    kind = Counter((x["split"], "regex" if "regex" in x["reason"] and "e5" not in x["reason"] else
                    "e5" if "regex" not in x["reason"] else "both") for x in flagged)
    out = {"benign_rows": len(benign), "flagged": len(flagged),
           "per_source_split": {f"{s}|{sp}": {"flagged": c, "benign_rows": benign_n[(s, sp)]} for (s, sp), c in sorted(counts.items())},
           "per_split_kind": {f"{sp}|{k}": c for (sp, k), c in sorted(kind.items())},
           "test_flagged": {sp: sum(x["split"] == sp for x in flagged) for sp in TEST_SPLITS},
           "policy": "drop flagged from train and dev; test sets unchanged (metrics with and without flagged rows)"}
    Path("results/label_audit.json").write_text(json.dumps(out, indent=2), encoding="utf-8")
    lines = ["# Label audit of benign rows", "", f"Generated by `scripts/label_audit.py`. {out['benign_rows']} benign rows scanned "
             "(English + Gemini translations; train, dev, test, overrefusal, email probe). Flags: jailbreak-marker regex on the text "
             "or its English original (wildjailbreak adversarial_benign excluded from regex), and multilingual-e5-small cosine > 0.95 "
             f"to any attack row. Flagged: {out['flagged']}. Rows: `data/processed/label_audit.csv` (not committed).", "",
             "| Source | Split | Flagged | Benign rows |", "|---|---|---:|---:|"]
    for k, v in out["per_source_split"].items():
        s, sp = k.split("|")
        lines.append(f"| {s} | {sp} | {v['flagged']} | {v['benign_rows']} |")
    lines += ["", f"By split and flag type: {json.dumps(out['per_split_kind'])}", "",
              f"Test-type sets flagged (kept, reported separately): {json.dumps(out['test_flagged'])}", "", f"Policy: {out['policy']}.", ""]
    Path("results/label_audit.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines), flush=True)


if __name__ == "__main__":
    main()
