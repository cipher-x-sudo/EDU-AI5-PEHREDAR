"""Build v2 classifier data (team decision 2026-11-26: no Urdu-script rows; ur translations reviewed 55.9% good).

train_v2.jsonl        = train_public_v2 + translated_v2 rows in roman_ur/mixed whose split_group is a train group,
                        minus every row marked "bad" in any review CSV; benign downsampled per language if the
                        attack:benign ratio is outside 1:1.2-1:1.8.
dev_v2_threshold.jsonl = dev_public_v2 + dev_translated_v2 rows in roman_ur/mixed (threshold selection only).
Writes results/v2_data.md."""
import csv, json, random
from collections import Counter
from pathlib import Path

ROOT = Path("data/processed")
LANGS = ("roman_ur", "mixed")
REVIEWS = ("translation_review_v2.csv", "translation_review_v2_abliterated.csv", "translation_review_v3.csv")
LO, HI = 1.2, 1.8


def read(name):
    return [json.loads(x) for x in (ROOT/name).read_text(encoding="utf-8").splitlines() if x.strip()]


def write(name, rows):
    (ROOT/name).write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8")


def balance(rows, rng):
    """Downsample benign per language so attack:benign <= 1:HI; report languages below 1:LO."""
    out, notes = [], {}
    for lang in sorted({r["lang"] for r in rows}):
        a = [r for r in rows if r["lang"] == lang and r["label"] == "attack"]
        b = [r for r in rows if r["lang"] == lang and r["label"] == "benign"]
        if len(b) > HI * len(a):
            b = rng.sample(sorted(b, key=lambda r: r["id"]), int(HI * len(a)))
            notes[lang] = "benign downsampled to 1:1.8"
        elif len(b) < LO * len(a):
            notes[lang] = "below 1:1.2 (not changed: only benign downsampling is allowed)"
        out += a + b
    return out, notes


def main():
    train = read("train_public_v2.jsonl")
    groups = {r["split_group"] for r in train}
    bad = {r["id"] for f in REVIEWS for r in csv.DictReader((ROOT/f).open(encoding="utf-8-sig"))
           if r["verdict"].strip().lower() == "bad"}
    trans = [r for r in read("translated_v2.jsonl") if r["lang"] in LANGS]
    kept = [r for r in trans if r["split_group"] in groups and r["id"] not in bad]
    rows, notes = balance(train + kept, random.Random(42))
    rows.sort(key=lambda r: r["id"])
    write("train_v2.jsonl", rows)
    dev = read("dev_public_v2.jsonl") + [r for r in read("dev_translated_v2.jsonl") if r["lang"] in LANGS]
    write("dev_v2_threshold.jsonl", dev)
    cell = lambda rs: {f"{l}/{b}": n for (l, b), n in sorted(Counter((r["lang"], r["label"]) for r in rs).items())}
    ratio = lambda rs: {l: round(sum(r["lang"] == l and r["label"] == "benign" for r in rs) /
                                 max(1, sum(r["lang"] == l and r["label"] == "attack" for r in rs)), 3)
                        for l in sorted({r["lang"] for r in rs})}
    report = {"decision": "no ur (Urdu script) rows in v2 training (team, 2026-11-26)",
              "translated_v2_candidates_roman_ur_mixed": len(trans),
              "removed_marked_bad_in_review": sum(r["id"] in bad for r in trans),
              "removed_not_train_group": sum(r["split_group"] not in groups for r in trans),
              "balance_notes": notes, "train_v2_rows": len(rows), "train_v2_by_lang_label": cell(rows),
              "train_v2_benign_per_attack": ratio(rows), "dev_v2_threshold_rows": len(dev),
              "dev_v2_threshold_by_lang_label": cell(dev)}
    Path("results/v2_data.md").write_text("# v2 classifier data\n\nGenerated by `scripts/build_v2_data.py`.\n\n```json\n"
                                          + json.dumps(report, indent=2) + "\n```\n", encoding="utf-8")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
